"""Regression coverage for complete, readable Modern CV exports."""
import re
from io import BytesIO

from django.template.loader import render_to_string
from django.test import SimpleTestCase
from pypdf import PdfReader

from .models import CV
from .modern_pdf import render_modern_pdf


class ModernPDFTests(SimpleTestCase):
    def cv(self, **changes):
        fields = dict(
            full_name="Example Candidate", job_title="Entry Level Web Developer",
            email="candidate.with.a.long.email.address@example.com",
            skills="Python, Django, PostgreSQL, OpenAI API, Stripe, Heroku\nResponsive design implementation and collaboration with team members",
            professional_summary="Built and deployed personal web applications.",
            experience="Example Employer\nIT Engineer\n2022-2025\n- Investigated infrastructure incidents.",
            education="Full Stack Development\nSolaris Systems Administrator",
            additional_sections=[{"title": "Projects", "content": "Weather Hub\n- Used Fetch API. https://example.com/portfolio"}],
        )
        fields.update(changes)
        return CV(**fields)

    def pdf(self, cv):
        reader = PdfReader(BytesIO(render_modern_pdf(cv).content))
        return reader, "\n".join(page.extract_text() for page in reader.pages)

    def test_full_skills_contacts_and_qualifications_survive_export(self):
        _, text = self.pdf(self.cv())
        flat = " ".join(text.split())
        self.assertIn("candidate.with.a.long.email.address@example.com", flat)
        self.assertIn("Responsive design implementation and collaboration with team members", flat)
        self.assertIn("Solaris Systems Administrator", text)
        self.assertNotIn("Generated by", text)

    def test_entry_level_projects_precede_employment_in_pdf_and_preview(self):
        cv = self.cv()
        _, text = self.pdf(cv)
        self.assertLess(text.index("Weather Hub"), text.index("Example Employer"))
        html = render_to_string("includes/modern_cv.html", {"cv": cv})
        self.assertLess(html.index("Weather Hub"), html.index("Example Employer"))

    def test_senior_role_keeps_employment_first(self):
        _, text = self.pdf(self.cv(job_title="Senior Web Developer", section_order=["professional_summary", "experience", "skills", "education", "additional:0"]))
        self.assertLess(text.index("Example Employer"), text.index("Weather Hub"))

    def test_long_skills_and_projects_continue_without_omitting_the_end(self):
        cv = self.cv(skills="\n".join(f"Detailed skill number {i}" for i in range(120)))
        cv.additional_sections[0]["content"] += "\n" + "\n".join(f"- Project evidence {i}" for i in range(120))
        reader, text = self.pdf(cv)
        self.assertGreater(len(reader.pages), 2)
        self.assertIn("Detailed skill number 119", text)
        self.assertIn("Project evidence 119", text)
        self.assertIn("Solaris Systems Administrator", text)
        urls = [annotation.get_object().get("/A", {}).get("/URI")
                for page in reader.pages for annotation in page.get("/Annots", [])]
        self.assertIn("https://example.com/portfolio", urls)

    def test_document_markup_is_text_and_long_tokens_fit_the_page(self):
        cv = self.cv(skills="<script>alert(1)</script>\n" + "X" * 250)
        _, text = self.pdf(cv)
        self.assertIn("<script>alert(1)</script>", text)
        self.assertEqual(sum(len(run) for run in re.findall(r"X{2,}", text)), 250)
        html = render_to_string("includes/modern_cv.html", {"cv": cv})
        self.assertNotIn("<script>", html)
        self.assertIn("&lt;script&gt;", html)


class EvidenceOrderTests(SimpleTestCase):
    def test_order_is_based_on_saved_evidence_ranking_across_all_exports(self):
        from .classic_pdf import render_classic_pdf
        from .executive_pdf import render_executive_pdf
        cases = [
            ("Web Developer", ["skills", "additional:0", "experience", "education"], "Project evidence", "Employment evidence"),
            ("Web Developer", ["experience", "skills", "additional:0", "education"], "Employment evidence", "Project evidence"),
            ("Teacher", ["education", "additional:1", "experience", "skills"], "Qualification evidence", "Employment evidence"),
            ("Community Coordinator", ["additional:1", "experience", "education", "skills"], "Volunteer evidence", "Employment evidence"),
        ]
        for title, order, first, second in cases:
            cv = CV(full_name="Applicant", job_title=title, skills="Skill evidence",
                    professional_summary="Summary evidence", experience="Employment evidence",
                    education="Qualification evidence", section_order=["professional_summary"] + order,
                    additional_sections=[{"title": "Projects", "content": "Project evidence"},
                                         {"title": "Volunteering", "content": "Volunteer evidence"}])
            for renderer in (render_modern_pdf, render_classic_pdf, render_executive_pdf):
                with self.subTest(role=title, renderer=renderer.__name__):
                    reader = PdfReader(BytesIO(renderer(cv).content))
                    text = "\n".join(page.extract_text() for page in reader.pages)
                    self.assertLess(text.index(first), text.index(second))
                    for evidence in ("Project evidence", "Volunteer evidence", "Employment evidence", "Qualification evidence"):
                        self.assertEqual(text.count(evidence), 1)
            for template in ("includes/modern_cv.html", "includes/classic_cv.html"):
                html = render_to_string(template, {"cv": cv})
                self.assertLess(html.index(first), html.index(second))

    def test_invalid_ranking_cannot_drop_duplicate_or_create_sections(self):
        cv = CV(full_name="Applicant", skills="Skill evidence", experience="Employment evidence",
                additional_sections=[{"title": "Projects", "content": "Project evidence"}],
                section_order=["additional:0", "additional:0", "invented", {"bad": "value"}, "additional:99"])
        sections = cv.modern_sections
        self.assertEqual([item["content"] for item in sections],
                         ["Project evidence", "Skill evidence", "Employment evidence"])
        cv.section_order = "experience"
        self.assertEqual(len(cv.modern_sections), 3)
