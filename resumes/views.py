@login_required
def job_match(request, id):
    """Compare an owned CV with pasted or uploaded job-description text."""
    cv = get_object_or_404(CV, id=id, user=request.user)

    analysis = None
    job_description = ""

    if request.method == "POST":
        # Accept either pasted text or an uploaded document.
        job_description = request.POST.get("job_description", "").strip()
        job_file = request.FILES.get("job_file")

        if job_file:
            # Read the job document directly; it is not a saved candidate CV.
            job_description = extract_text_from_cv(job_file)

        if job_description:
            # Keep the latest job context available to cover-letter generation.
            request.session["last_job_description"] = job_description
            request.session["last_job_cv_id"] = cv.id

            ai = AIService()

            analysis = normalise_analysis(ai.analyse_job_description(cv_matching_text(cv), job_description))
            request.session["last_job_analysis"] = analysis
            request.session["last_job_match_fingerprint"] = match_fingerprint(cv, job_description)

            return render(request, "job_match.html", job_match_context(
                cv, job_description, analysis, message="Job description analysed successfully.",
            ))

        return render(request, "job_match.html", job_match_context(
            cv, message="Please paste or upload a job description first.", message_level="warning",
        ))

    # Keep the latest results visible when returning to this unchanged CV.
    job_description = request.session.get("last_job_description", "")
    if request.session.get("last_job_match_fingerprint") == match_fingerprint(cv, job_description):
        analysis = normalise_analysis(request.session.get("last_job_analysis"))
    else:
        job_description = ""
    return render(request, "job_match.html", job_match_context(cv, job_description, analysis))


@login_required
@enforce_cv_limit
def tailor_cv_to_job(request, id):
    """Create a new CV variant rewritten for a supplied job description."""
    cv = get_object_or_404(CV, id=id, user=request.user)

    if request.method == "POST":
        job_description = request.POST.get("job_description", "").strip()

        if not job_description:
            return redirect("job_match", id=cv.id)

        # Accept only a server-held result for this exact CV and job description.
        if request.session.get("last_job_match_fingerprint") != match_fingerprint(cv, job_description):
            return render(request, "job_match.html", job_match_context(
                cv, job_description, message_level="warning",
                message="Analyse this CV against this job description before tailoring. If you changed either, analyse again.",
            ), status=400)

        analysis = normalise_analysis(request.session.get("last_job_analysis"))
        score = analysis["match_score"]
        if score is None or score < MIN_TAILOR_MATCH_SCORE:
            return render(request, "job_match.html", job_match_context(
                cv, job_description, analysis,
            ), status=403)

        ai = AIService()
        # Never overwrite the source CV: request tailored structured field data.
        tailored_data = ai.tailor_cv_to_job(cv_matching_text(cv), job_description)
        from .tailoring_guard import protect_source_sections

        tailored_data, restored = protect_source_sections(cv, tailored_data)
        if restored:
            messages.warning(request, "Some AI suggestions omitted source details or changed section boundaries. "
                             "The affected sections were kept from your original CV. Please review the result.")


        from .cv_layout import normalise_section_order

        section_order = normalise_section_order(tailored_data.get("section_order"), cv.additional_sections)

        # Avoid repeatedly appending the suffix when tailoring an existing copy.
        base_name = cv.full_name.split(" - Tailored CV")[0]

        # Insert a separate CV, preserving contact details and falling back to
        # original sections whenever the AI omits a value.
        tailored_cv = CV.objects.create(
            user=request.user,
            full_name=f"{base_name} - Tailored CV",
            email=cv.email,
            phone=cv.phone,
            address=cv.address,
            job_title=tailored_data.get("job_title") or cv.job_title,
            professional_summary=tailored_data.get("professional_summary")
            or cv.professional_summary,
            skills=tailored_data.get("skills") or cv.skills,
            experience=tailored_data.get("experience") or cv.experience,
            education=tailored_data.get("education") or cv.education,
            additional_sections=cv.additional_sections,
            section_order=section_order or cv.section_order,
            template=cv.template,
            original_content={name: getattr(cv, name) or "" for name in TailoredCVReviewForm.Meta.fields},
        )

        return redirect("review_tailored_cv", id=tailored_cv.id)

    return redirect("job_match", id=cv.id)


@login_required
def review_tailored_cv(request, id):
    """Compare a tailored CV with its source snapshot and allow corrections."""
    from difflib import SequenceMatcher

    cv = get_object_or_404(CV, id=id, user=request.user)
    if not cv.original_content:
        return redirect("edit_cv", id=cv.id)
    form = TailoredCVReviewForm(request.POST or None, instance=cv)
    if request.method == "POST" and form.is_valid():
        form.save()
        return redirect(f"{reverse('dashboard')}?cv={cv.pk}#dashboard-preview")

    sections = []
    for field in form:
        original = cv.original_content.get(field.name, "") or ""
        current = str(field.value() or "")
        before, after = [], []
        old_words, new_words = original.split(), current.split()
        for tag, i, j, k, l in SequenceMatcher(None, old_words, new_words, autojunk=False).get_opcodes():
            if i != j:
                before.append({"text": " ".join(old_words[i:j]), "changed": tag != "equal"})
            if k != l:
                after.append({"text": " ".join(new_words[k:l]), "changed": tag != "equal"})
        sections.append({"field": field, "changed": original != current, "before": before, "after": after})
    return render(request, "review_tailored_cv.html", {"cv": cv, "form": form, "sections": sections})
