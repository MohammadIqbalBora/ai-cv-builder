@login_required
def dashboard(request):
    """Render the user's dashboard with their CV list and subscription status."""
    # Fetch only this user's CVs, newest first; this also prevents data leakage.
    cvs = CV.objects.filter(user=request.user).order_by("-created_at")

    # Recover letters generated by older releases, which only used the session.
    legacy_content = request.session.get("last_cover_letter")
    legacy_cv_id = request.session.get("last_cover_letter_cv_id")
    if legacy_content and legacy_cv_id:
        legacy_cv = cvs.filter(id=legacy_cv_id).first()
        if legacy_cv:
            CoverLetter.objects.get_or_create(
                user=request.user,
                cv=legacy_cv,
                content=legacy_content,
                defaults={"job_description": request.session.get("last_job_description", "")},
            )
            request.session.pop("last_cover_letter", None)
            request.session.pop("last_cover_letter_cv_id", None)

    cover_letters = CoverLetter.objects.filter(user=request.user).select_related("cv").order_by("-created_at")
    selected_letter = None
    if request.GET.get("letter"):
        selected_letter = get_object_or_404(cover_letters, pk=request.GET["letter"])

    selected_cv = None
    # A `?cv=ID` query string lets the page request one selected CV.
    selected_cv_id = request.GET.get("cv")

    # `.first()` returns None rather than raising when the ID is not owned/found.
    if selected_cv_id:
        selected_cv = cvs.filter(id=selected_cv_id).first()

    # Default to the newest CV when no valid explicit selection exists.
    if not selected_cv and cvs.exists():
        selected_cv = cvs.first()

    if selected_letter:
        selected_cv = selected_letter.cv
    latest_cv_letter = cover_letters.filter(cv=selected_cv).first() if selected_cv else None

    # Subscription is optional, so retrieve the row without requiring one.
    subscription = Subscription.objects.filter(user=request.user).first()

    is_premium = False
    plan_name = "Free"

    # Convert database state into simple values the template can display.
    if subscription and subscription.has_premium_access:
        is_premium = True
        plan_name = subscription.plan_name

    # Evaluate the QuerySet count in the database for the dashboard statistic.
    total_cvs = cvs.count()

    return render(
        request,
        "dashboard.html",
        {
            "cvs": cvs,
            "selected_cv": selected_cv,
            "total_cvs": total_cvs,
            "cover_letters": cover_letters,
            "selected_letter": selected_letter,
            "latest_cv_letter": latest_cv_letter,
            "is_premium": is_premium,
            "plan_name": plan_name,
        },
    )


def parse_cv_with_ai_or_fallback(extracted_text):
    """Use AI parsing when available, retaining local parsing as a fallback."""
    try:
        data = AIService().parse_uploaded_cv(extracted_text)
        if not isinstance(data, dict):
            raise ValueError("CV parser must return a dictionary")
        from .ai_service import make_plain_text
        from .validators import validate_additional_sections
        sections = data.get("additional_sections", [])
        validate_additional_sections(sections)
        titles = {section["title"].strip().casefold() for section in sections}
        for section in extract_additional_sections(extracted_text):
            existing = next((item for item in sections if item["title"].strip().casefold() == section["title"].casefold()), None)
            # Preserve source project links and their association with each project.
            if existing and ("https://" in section["content"] or "http://" in section["content"]):
                existing["content"] = section["content"]
            elif section["title"].casefold() not in titles:
                sections.append(section)
        validate_additional_sections(sections)
        result = {key: make_plain_text(value) for key, value in data.items() if key != "additional_sections"}
        fallback = parse_cv_text(extracted_text)
        # Employment history is factual source text: do not let an AI rewrite
        # drop employers, job titles, dates, or responsibilities.
        if fallback.get("experience"):
            result["experience"] = fallback["experience"]
        for key, value in fallback.items():
            if key != "additional_sections" and not result.get(key):
                result[key] = value
        result["additional_sections"] = sections
        return result
    except Exception:
        logger.warning("AI CV parsing failed; using local parsing", exc_info=True)
        return parse_cv_text(extracted_text)


def import_data_into_cv(cv, parsed_data):
    """Copy parsed CV values into the CV model and save it."""
    # For every field, prefer a non-empty parsed value and otherwise retain the
    # value already stored on the CV. This prevents blank AI output erasing data.
    cv.full_name = parsed_data.get("full_name") or cv.full_name
    cv.job_title = parsed_data.get("job_title") or cv.job_title
    cv.email = parsed_data.get("email") or cv.email
    cv.phone = parsed_data.get("phone") or cv.phone
    cv.address = parsed_data.get("address") or cv.address

    cv.professional_summary = (
        parsed_data.get("professional_summary") or cv.professional_summary
    )

    cv.skills = parsed_data.get("skills") or cv.skills
    cv.experience = parsed_data.get("experience") or cv.experience
    cv.education = parsed_data.get("education") or cv.education

    cv.additional_sections = merge_additional_sections(
        cv.additional_sections or [], parsed_data.get("additional_sections", [])
    )

    # Persist all assignments in one database update.
    cv.save()





def enforce_cv_limit(view):
    """Serialize CV creation per account so parallel requests cannot exceed quota."""
    from functools import wraps
    from django.db import transaction

    @wraps(view)
    def wrapped(request, *args, **kwargs):
        with transaction.atomic():
            # All creation routes lock the same account, including for Premium.
            get_user_model().objects.select_for_update().get(pk=request.user.pk)
            if (not user_has_active_subscription(request.user)
                    and CV.objects.filter(user=request.user).count() >= 3):
                return render(request, "cv_limit.html", status=403)
            return view(request, *args, **kwargs)
    return wrapped


@login_required
@enforce_cv_limit
def create_cv(request):
    """Create a new CV record or import an uploaded CV file via AI parsing."""
    # Create CV: GET = show me the blank form
    # Save CV: POST = here is my completed form
    if request.method == "POST":
        # The submit button identifies whether this is an import or normal save.
        action = request.POST.get("action")

        # Import CV using AI - do NOT validate empty form fields first
        if action == "import":
            # Uploaded binary files live in request.FILES, not request.POST.
            uploaded_file = request.FILES.get("uploaded_file")

            if not uploaded_file:
                # Bind both dictionaries so the page can redisplay its values.
                form = CVForm(request.POST, request.FILES)
                form.add_error("uploaded_file", "Please choose a CV file to import.")
                return render(request, "create_cv.html", {"form": form})

            form = CVForm(request.POST, request.FILES)
            if not uploaded_file.name.lower().endswith((".pdf", ".docx")):
                form.add_error("uploaded_file", "Please upload a PDF or DOCX file.")
                return render(request, "create_cv.html", {"form": form})

            # Preserve manually entered extra sections when importing a CV.
            from django.core.exceptions import ValidationError
            try:
                additional_sections = form.fields["additional_sections"].clean(form["additional_sections"].data)
            except ValidationError as error:
                form.add_error("additional_sections", error)
                return render(request, "create_cv.html", {"form": form})

            # Extract directly from the upload before saving any database record.
            try:
                from .cv_parser import extract_text_from_pdf, extract_text_from_docx
                extractor = extract_text_from_pdf if uploaded_file.name.lower().endswith(".pdf") else extract_text_from_docx
                extracted_text = extractor(uploaded_file)
            except Exception:
                logger.warning("Could not read uploaded CV", exc_info=True)
                form.add_error("uploaded_file", "This file could not be read. Please upload a valid PDF or DOCX.")
                return render(request, "create_cv.html", {"form": form})

            if not extracted_text.strip():
                form.add_error("uploaded_file", "No readable text was found. Please upload a text-based PDF or DOCX rather than a scanned image.")
                return render(request, "create_cv.html", {"form": form})

            parsed_data = parse_cv_with_ai_or_fallback(extracted_text)
            try:
                additional_sections = merge_additional_sections(
                    additional_sections, parsed_data.get("additional_sections", [])
                )
            except ValidationError as error:
                form.add_error("additional_sections", error)
                return render(request, "create_cv.html", {"form": form})
            uploaded_file.seek(0)
            template = request.POST.get("template", "modern")
            if template not in dict(CV.TEMPLATE_CHOICES):
                template = "modern"
            cv = CV.objects.create(
                user=request.user,
                full_name="",
                uploaded_file=uploaded_file,
                template=template,
                additional_sections=additional_sections,
            )
            import_data_into_cv(cv, parsed_data)

            # Let the user review and correct imported fields.
            return redirect("edit_cv", id=cv.id)

        # Normal save CV
        # Bind normal text fields and an optional uploaded file to CVForm.
        # The below line refers to: resumes/forms.py
        form = CVForm(request.POST, request.FILES)

        if form.is_valid():
            # Delay the insert because the form deliberately does not expose
            # the `user` field; ownership must come from the logged-in request.

            # Creates the CV object in Python but does not save it to the database yet. #
            # This gives the view time to add information that was deliberately excluded from the form #
            cv = form.save(commit=False)
            cv.user = request.user
            cv.save()
            return redirect("dashboard")

    else:
        # GET requests display a blank creation form.
        form = CVForm()
    # The below refers to resume/forms.py
    return render(request, "create_cv.html", {"form": form})


@login_required
def edit_cv(request, id):
    """Edit an existing CV and show which fields are still missing."""
    # Filtering by both ID and user prevents one account editing another's CV.
    cv = get_object_or_404(CV, id=id, user=request.user)

    # Build human-readable reminders for every empty optional section.
    missing_fields = []

    if not cv.email:
        missing_fields.append("Email")
    if not cv.phone:
        missing_fields.append("Phone")
    if not cv.address:
        missing_fields.append("Address")
    if not cv.job_title:
        missing_fields.append("Job Title")
    if not cv.professional_summary:
        missing_fields.append("Professional Profile")
    if not cv.skills:
        missing_fields.append("Skills")
    if not cv.experience:
        missing_fields.append("Experience")
    if not cv.education:
        missing_fields.append("Education")

    if request.method == "POST":
        # `instance=cv` changes ModelForm.save() from INSERT to UPDATE.
        form = CVForm(request.POST, request.FILES, instance=cv)

        if form.is_valid():
            form.save()
            return redirect("dashboard")

    else:
        # Prepopulate the form fields from the existing database object.
        form = CVForm(instance=cv)

    return render(
        request,
        "create_cv.html",
        {
            "form": form,
            "cv": cv,
            "missing_fields": missing_fields,
        },
    )


