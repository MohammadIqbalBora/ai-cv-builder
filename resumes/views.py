@login_required
def create_cover_letter(request, id):
    """Generate a cover letter from a pasted, uploaded, or previously analysed job."""
    cv = get_object_or_404(CV, id=id, user=request.user)

    saved_letter = None
    if request.GET.get("letter"):
        saved_letter = get_object_or_404(
            CoverLetter, id=request.GET["letter"], cv=cv, user=request.user
        )
        if request.method == "GET":
            return redirect(f"{reverse('dashboard')}?letter={saved_letter.pk}#dashboard-preview")
    else:
        saved_letter = CoverLetter.objects.filter(cv=cv, user=request.user).order_by("-created_at").first()
    cover_letter = saved_letter.content if saved_letter else None
    # Job matching stores the most recent description in this browser session.
    job_description = request.session.get("last_job_description", "")

    if request.method == "POST":
        job_description = request.POST.get("job_description", job_description).strip()
        job_file = request.FILES.get("job_file")
        error = ""
        if job_file:
            if not job_file.name.lower().endswith((".pdf", ".docx")):
                error = "Please upload a PDF or Word (.docx) document."
            else:
                try:
                    job_description = extract_text_from_cv(job_file).strip()
                except Exception:
                    error = "This document could not be read. Please upload another file or paste the job description."
                if not error and not job_description:
                    error = "No text was found in this document. Please paste the job description or upload a document containing text."
        if not job_description:
            error = error or "Please paste a job description or upload a PDF or Word document."
        if error:
            return render(request, "cover_letter.html", {
                "cv": cv, "cover_letter": cover_letter, "saved_letter": saved_letter,
                "job_description": job_description, "error": error,
            }, status=400)

        ai = AIService()

        cv_text = cv_matching_text(cv)
        cover_letter = ai.generate_cover_letter(cv_text, job_description)
        saved_letter = CoverLetter.objects.create(
            user=request.user, cv=cv, job_description=job_description, content=cover_letter
        )
        return redirect(f"{reverse('dashboard')}?letter={saved_letter.pk}#dashboard-preview")

    return render(
        request,
        "cover_letter.html",
        {
            "cv": cv,
            "cover_letter": cover_letter,
            "saved_letter": saved_letter,
            "job_description": job_description,
        },
    )


def enforce_download_limit(view):
    from functools import wraps
    from django.db import transaction

    @wraps(view)
    def wrapped(request, id):
        # Reject unowned documents before checking or consuming the allowance.
        get_object_or_404(CV, id=id, user=request.user)
        with transaction.atomic():
            get_user_model().objects.select_for_update().get(pk=request.user.pk)
            premium = user_has_active_subscription(request.user)
            usage = None
            pack = None
            credit_field = "letter_downloads" if view.__name__ == "download_cover_letter_pdf" else "cv_downloads"
            if not premium:
                pack = ApplicationPack.objects.filter(user=request.user, **{credit_field + "__gt": 0}).order_by("created_at").first()
                if not pack:
                    usage, _ = FreeDownloadUsage.objects.get_or_create(user=request.user)
                    if usage.downloads >= 3:
                        return render(request, "download_limit.html", status=403)
            request.clean_document_download = premium or pack is not None
            response = view(request, id)
            if response.status_code == 200 and response.get("Content-Type") == "application/pdf":
                if pack:
                    setattr(pack, credit_field, getattr(pack, credit_field) - 1)
                    pack.save(update_fields=[credit_field])
                elif usage is not None:
                    usage.downloads += 1
                    usage.save(update_fields=["downloads"])
            return response
    return wrapped


